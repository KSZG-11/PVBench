def category_of(dimension: str) -> str:
    """返回维度所属的 D 大类编号 (如 "D4")。未知维度返回 None。"""
    return DIMENSION_TO_CATEGORY.get(dimension)


def category_name(category_id: str) -> str:
    """返回 D 大类名 (如 "D4" -> "几何与空间一致性")。"""
    meta = DIMENSION_CATEGORIES_META.get(category_id)
    return meta[0] if meta else category_id


def group_dimensions_by_category() -> dict:
    """按 D 大类分组返回维度列表 {D1: [...], D2: [...], ...}。"""
    grouped = {cat_id: [] for cat_id in DIMENSION_CATEGORIES_META}
    for dim, cat in DIMENSION_TO_CATEGORY.items():
        grouped[cat].append(dim)
    return grouped
