class MaterialEvaluator(VLMBaseEvaluator):
    """材料属性评测器 (R06, Qwen3.8-27B)"""

    def __init__(self, vlm, config: Optional[dict] = None):
        super().__init__(vlm, "L3-Physics/Material", config)

    def evaluate(self, frames: list[Image.Image],
                 expected_materials: Optional[list] = None) -> list[EvalResult]:
        matrix = "\n".join(f"- {k}: {v}" for k, v in MATERIAL_MATRIX.items())
        expected = (f"\n期望材料(参考): {', '.join(expected_materials)}"
                    if expected_materials else "")
        prompt = f"""你是材料物理专家，分析视频中每个物体的材料行为是否符合物理规律。{expected}

请客观识别视频中出现的物体及其材料。若视频中没有可判定材料行为的力学事件（无接触、无受力、无形变），应如实说明。

【材料标准行为矩阵 — 7大类30+子类】
{matrix}

【行为维度】
- 固体: 刚度 / 脆性 / 弹性 / 密度(浮沉) / 摩擦
- 流体与软体: 粘度 / 表面张力 / 可压性 / 褶皱垂坠 / 摆动阻尼 / 颗粒流变

【评测流程】
1) 识别每个物体的材料类别(对应上表某一子类)
2) 提取关键力学事件(碰撞/挤压/坠落/倾倒/加热/浸水等)
3) 逐行为维度描述实际观测到的表现
4) 与上表该材料的标准行为比对
5) 逐维 1-5 分 + 跨帧一致性扣分(同一物体材质不应突变)
6) 汇总为综合分

【评分标准】
5= 行为与该材料类别标准矩阵完全一致
3 = 方向对但细节反常(如玻璃碎了但碎片形态不对)
1 = 行为与材料根本不符

【典型违例】玻璃弯曲不碎 / 石头被压扁 / 金属如布飘动 / 橡胶不回弹 / 铁浮水面 /
水向上流 / 油水互溶 / 蜜如水般速流 / 布料僵硬不垂坠 / 沙如刚体整块移动 /
烟如固体块 / 纸浸水仍硬挺 / 同一物体跨帧材质突变

【关键判定】先判断视频中是否真的存在可判定材料行为的力学事件:
- has_mechanical_event: 视频中是否出现碰撞/挤压/坠落/倾倒/加热/浸水/流动等力学事件? true/false
- 若 has_mechanical_event=false (视频没有生成 prompt 要求的材料/力学事件, 只是静态或无关画面),
  说明生成模型未完成任务, score 必须给 1 分(严重不达标), 并在 violations 说明"视频未生成可判定的材料行为事件"。

返回 JSON: {{"score": <1-5整数>, "has_mechanical_event": <true/false>, "reason": "一句话总结评估",
"identified_materials": ["物体:材料类别"], "violations": ["..."]}}"""
        return [self._score_with_json(frames, "R06-材料属性", prompt,
                                      n_frames=6, max_new_tokens=1024)]
